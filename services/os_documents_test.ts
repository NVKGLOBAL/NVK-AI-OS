/**
 * OS documents.create test (matrix item 5, 2026-11-27).
 *
 * Pure-module test — no server, no DOM, no model, no network. Verifies
 * the persistence contract end to end:
 *   (1) create a document from REAL input -> it is stored;
 *   (2) a FRESH store handle reads it back (create -> persist ->
 *       reload/read-back), with the exact content supplied;
 *   (3) the download payload is the real document (title, content,
 *       Markdown filename, text/markdown MIME) — the Blob download in
 *       the panel is built from this payload;
 *   (4) update and delete round-trip through the same store;
 *   (5) the real documents.create capability creates from real input,
 *       verifies against the persistent store (not just the in-memory
 *       artifact map), and REFUSES to invent content — missing content
 *       or a missing title is an honest error, never the old fixed
 *       template ("Generated by NVK Global Intelligence…").
 *
 * Run: npx tsx services/os_documents_test.ts
 * (coordinator wires it into `npm test`; it needs no server).
 * Note: under tsx/Node there is no IndexedDB, so the store runs in its
 * in-memory fallback — the same API, same round-trip; in the browser
 * the Dexie table is the durable store.
 */
import { DocumentStore, documentStore, documentDownload, documentToMarkdown } from './DocumentStore';
import { capabilityRegistry } from '../src/nvk/capabilities/CapabilityRegistry';

let failures = 0;
const check = (name: string, ok: boolean, detail = '') => {
  if (ok) {
    console.log(`  PASS ${name}`);
  } else {
    failures++;
    console.error(`  FAIL ${name} ${detail}`);
  }
};

const REAL_TITLE = 'NVK Global — Test Brief 2026-11-27';
const REAL_CONTENT = '# Real brief\n\nWritten by the test, not a template.\n\n- First real point\n- Second real point\n';
const REAL_SLIDES = [
  { title: 'Real Slide One', subtitle: 'Written by the test', point: 'The first real point.' },
  { title: 'Real Slide Two', subtitle: '', point: 'The second real point.', metrics: [{ label: 'Real metric', value: '7' }] },
];

console.log('DocumentStore: create -> persist -> reload/read-back:');
const created = await documentStore.createDocument({
  title: REAL_TITLE,
  type: 'document',
  content: REAL_CONTENT,
});
check('created document keeps the exact title and content supplied',
  created.title === REAL_TITLE && created.content === REAL_CONTENT);
check('created document has a stable id and timestamps',
  typeof created.id === 'string' && created.id.startsWith('doc-')
  && created.createdAt > 0 && created.updatedAt >= created.createdAt);
{
  // Reload/read-back through a FRESH store handle — the read path a
  // reload takes, not the same in-memory object.
  const freshStore = new DocumentStore();
  const reloaded = await freshStore.getDocument(created.id);
  check('a fresh store handle reads the document back with identical content',
    reloaded !== undefined && reloaded.title === REAL_TITLE && reloaded.content === REAL_CONTENT,
    JSON.stringify(reloaded)?.slice(0, 200));
  const byTitle = await freshStore.getDocumentByTitle(REAL_TITLE);
  check('read-back by title finds the same document',
    byTitle !== undefined && byTitle.id === created.id);
  const listed = await freshStore.listDocuments();
  check('listDocuments includes the created document',
    listed.some((d) => d.id === created.id));
}
{
  const payload = documentDownload(created);
  check('download payload filename is a Markdown file named from the real title',
    payload.filename.endsWith('.md') && payload.filename.includes('NVK_Global'),
    payload.filename);
  check('download payload MIME is text/markdown',
    payload.mimeType === 'text/markdown');
  check('download payload contains the real content — nothing templated',
    payload.content.includes('Written by the test, not a template.')
    && payload.content.includes('# NVK Global — Test Brief 2026-11-27')
    && !payload.content.includes('Generated by NVK Global Intelligence'));
}
{
  const updated = await documentStore.updateDocument(created.id, {
    content: '# Updated brief\n\nEdited content, still real.\n',
  });
  check('update persists new content',
    updated.content.includes('Edited content, still real.'));
  const reloaded = await new DocumentStore().getDocument(created.id);
  check('updated content reads back through a fresh handle',
    reloaded !== undefined && reloaded.content.includes('Edited content, still real.'));
}
{
  const deleted = await documentStore.deleteDocument(created.id);
  const gone = await new DocumentStore().getDocument(created.id);
  check('delete removes the document (read-back finds nothing)',
    deleted === true && gone === undefined);
}
{
  let threw = '';
  try {
    await documentStore.createDocument({ title: '   ', content: 'x' });
  } catch (e: any) {
    threw = e?.message || '';
  }
  check('a document with no title is refused, not created blank',
    /TITLE_REQUIRED/.test(threw));
  const missing = await documentStore.getDocument('doc-does-not-exist');
  check('reading a missing id returns undefined, not a fabricated document',
    missing === undefined);
  let updateThrew = '';
  try {
    await documentStore.updateDocument('doc-does-not-exist', { content: 'x' });
  } catch (e: any) {
    updateThrew = e?.message || '';
  }
  check('updating a missing id throws, not a silent create',
    /NOT_FOUND/.test(updateThrew));
}

console.log('documentToMarkdown (deck rendering):');
{
  const deck = await documentStore.createDocument({
    title: 'Real Deck',
    type: 'pitch_deck',
    slides: REAL_SLIDES,
  });
  const md = documentToMarkdown(deck);
  check('a deck renders its REAL slides as Markdown sections',
    md.includes('## Slide 1: Real Slide One')
    && md.includes('The first real point.')
    && md.includes('- Real metric: 7'));
  check('deck content is derived from the real slides, not a template',
    !md.includes('Generated by NVK Global Intelligence')
    && !md.includes('Executive Summary'));
  await documentStore.deleteDocument(deck.id);
}

console.log('documents.create capability:');
{
  const cap = capabilityRegistry.getCapability('documents.create');
  check('documents.create is registered and available', !!cap && cap.available === true);
  const out: any = await cap!.execute({
    title: 'Capability Test Doc',
    content: 'Capability content — written for this test.\n\nSecond paragraph, also real.',
  });
  check('capability creates from real input and returns the document id',
    typeof out.artifactId === 'string' && out.artifactId.startsWith('doc-')
    && typeof out.documentId === 'string');
  check('capability returns a download payload (filename + MIME)',
    out.download?.filename === 'Capability_Test_Doc.md' && out.download?.mimeType === 'text/markdown',
    JSON.stringify(out.download));
  check('capability verify() reads the document back from the persistent store',
    (await cap!.verify!({}, out)) === true);
  const stored = await new DocumentStore().getDocument(out.documentId);
  check('the created document persists and reads back with the real content',
    stored !== undefined && stored.content.includes('Capability content — written for this test.'));
  check('stored content is the supplied content, not the old fixed template',
    stored !== undefined
    && !stored.content.includes('Generated by NVK Global Intelligence')
    && !stored.content.includes('Strategic Recommendations'));
  await documentStore.deleteDocument(out.documentId);
}
{
  const cap = capabilityRegistry.getCapability('documents.create');
  let threw = '';
  try {
    await cap!.execute({ title: 'No Content Doc' });
  } catch (e: any) {
    threw = e?.message || '';
  }
  check('missing content is an honest error — no template is substituted',
    /DOCUMENT_CONTENT_REQUIRED/.test(threw), threw);
  let titleThrew = '';
  try {
    await cap!.execute({ content: 'Content with no title at all.' });
  } catch (e: any) {
    titleThrew = e?.message || '';
  }
  check('a missing title is an honest error',
    /DOCUMENT_TITLE_REQUIRED/.test(titleThrew), titleThrew);
  const out: any = await cap!.execute({
    title: 'Slides Only Deck',
    type: 'pitch_deck',
    slides: REAL_SLIDES,
  });
  check('real slides alone create a deck (content derived from the slides)',
    typeof out.artifactId === 'string' && out.artifactId.startsWith('doc-'));
  const stored = await new DocumentStore().getDocument(out.documentId);
  check('the slides-only deck persists with its real slides',
    stored !== undefined && Array.isArray(stored.slides) && stored.slides.length === 2
    && stored.slides[0].title === 'Real Slide One');
  await documentStore.deleteDocument(out.documentId);
}

if (failures > 0) {
  console.error(`\n${failures} check(s) failed.`);
  process.exit(1);
}
console.log('\nAll OS documents.create checks passed.');
