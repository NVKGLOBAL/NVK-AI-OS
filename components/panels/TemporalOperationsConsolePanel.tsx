  const handleInitiateDirective = () => {
    if (selectedDirective) {
      const operation = directiveOptions_Phase9_5_EmeraldCodex.find(op => op.id === selectedDirective);
      let commandToExecute = operation?.command || 'No command specified';
      let labelForLog = operation?.label || 'Unknown operation';
      
      const eventData: HistoricalSeekerInputEventData = {
        inputType: 'CultivationDirective',
        inputValue: `Execute Hermetic Operation (Phase 9.5): ${commandToExecute}`,
        panelContext: 'TemporalOperationsConsolePanel - Phase 9.5: Emerald Codex',
        details: `Selected operation: ${labelForLog}`
      };
      addEchoMessage(
        AgentName.TemporalOperationsAgent, 
        `Initiating Hermetic Operation (Phase 9.5): ${labelForLog}. Invoking: ${commandToExecute}`,
        AGENT_PROFILES[AgentName.TemporalOperationsAgent]?.colorClass || AGENT_PROFILES[AgentName.SystemControl]?.colorClass,
        false,
        { eventType: HistoricalEventType.SEEKER_INPUT, eventData }
      );
      addEchoMessage(AgentName.SystemControl, `Operation "${labelForLog}" confirmed for Phase 9.5. The Emerald Currents flow.`, 'text-cyan-300');
      
    } else {
      addEchoMessage(AgentName.SystemControl, "No Hermetic Operation selected for Phase 9.5.", 'text-yellow-400');
    }
  };
  
